/**
 * 将图片像素点阵二值化并执行定向 1-像素噪线与毛刺剥离。
 *
 * @param rgbaData 图像的 RGBA 像素一维数组 (4 * width * height)
 * @param width 图像宽度（强智标准为 70~75px）
 * @param height 图像高度（强智标准为 27~30px）
 * @returns 预处理后的二维二值矩阵 [y][x] (1 为笔画，0 为背景)
 */
function preprocessPixels(rgbaData: Uint8ClampedArray | Uint8Array, width: number, height: number): number[][] {
  const grid: number[][] = Array.from({ length: height }, () => new Array(width).fill(0));

  // 1. 灰度阈值二值化（忽略最外侧 2 像素边框）
  for (let y = 2; y < height - 2; y++) {
    for (let x = 2; x < width - 2; x++) {
      const idx = (y * width + x) * 4;
      const r = rgbaData[idx];
      const g = rgbaData[idx + 1];
      const b = rgbaData[idx + 2];
      const gray = 0.299 * r + 0.587 * g + 0.114 * b;
      if (gray < 170) {
        grid[y][x] = 1;
      }
    }
  }

  // 2. 迭代式 1-像素对角噪线与毛刺剥离 (2 轮扫描)
  for (let round = 0; round < 2; round++) {
    const toRemove: [number, number][] = [];
    for (let y = 1; y < height - 1; y++) {
      for (let x = 1; x < width - 1; x++) {
        if (grid[y][x] === 1) {
          const isDiag1 = (grid[y - 1][x - 1] === 1 || grid[y + 1][x + 1] === 1) &&
            grid[y - 1][x] === 0 && grid[y + 1][x] === 0 && grid[y][x - 1] === 0 && grid[y][x + 1] === 0;
          const isDiag2 = (grid[y - 1][x + 1] === 1 || grid[y + 1][x - 1] === 1) &&
            grid[y - 1][x] === 0 && grid[y + 1][x] === 0 && grid[y][x - 1] === 0 && grid[y][x + 1] === 0;

          let neighbors = 0;
          for (let dy = -1; dy <= 1; dy++) {
            for (let dx = -1; dx <= 1; dx++) {
              if ((dy !== 0 || dx !== 0) && grid[y + dy][x + dx] === 1) {
                neighbors++;
              }
            }
          }

          if (isDiag1 || isDiag2 || neighbors < 2) {
            toRemove.push([y, x]);
          }
        }
      }
    }
    for (const [ry, rx] of toRemove) {
      grid[ry][rx] = 0;
    }
  }

  return grid;
}

/**
 * 垂直投影切分 4 个字符区间并映射至 14x36 排版画布。
 *
 * @param grid 二维二值矩阵 [y][x]
 * @param width 宽度
 * @param height 高度
 * @returns 4 个字符的 14x36 标准点阵矩阵
 */
function extractTypographyBlocks(grid: number[][], width: number, height: number): number[][][] {
  const xProj: number[] = new Array(width).fill(0);
  for (let x = 0; x < width; x++) {
    for (let y = 0; y < height; y++) {
      if (grid[y][x] === 1) xProj[x]++;
    }
  }

  let intervals: [number, number][] = [];
  let inBlock = false;
  let startX = 0;

  for (let x = 0; x < width; x++) {
    if (xProj[x] > 0 && !inBlock) {
      inBlock = true;
      startX = x;
    } else if (xProj[x] === 0 && inBlock) {
      inBlock = false;
      if (x - startX >= 3) {
        intervals.push([startX, x - 1]);
      }
    }
  }
  if (inBlock && width - startX >= 3) {
    intervals.push([startX, width - 1]);
  }

  // 补齐至 4 个字符
  while (intervals.length < 4) {
    let widestIdx = -1;
    let maxWidth = 0;
    for (let i = 0; i < intervals.length; i++) {
      const w = intervals[i][1] - intervals[i][0] + 1;
      if (w > maxWidth) {
        maxWidth = w;
        widestIdx = i;
      }
    }
    if (widestIdx === -1 || maxWidth < 18) break;
    const [sx, ex] = intervals[widestIdx];
    const mid = Math.floor((sx + ex) / 2);
    let minVal = 999;
    let cutX = mid;
    for (let x = mid - 3; x <= mid + 3; x++) {
      if (x >= 0 && x < width && xProj[x] < minVal) {
        minVal = xProj[x];
        cutX = x;
      }
    }
    intervals.splice(widestIdx, 1, [sx, cutX], [cutX + 1, ex]);
  }

  // 合并多余碎片
  while (intervals.length > 4) {
    let narrowestIdx = -1;
    let minW = 999;
    for (let i = 0; i < intervals.length; i++) {
      const w = intervals[i][1] - intervals[i][0] + 1;
      if (w < minW) {
        minW = w;
        narrowestIdx = i;
      }
    }
    if (narrowestIdx === -1) break;
    if (narrowestIdx > 0) {
      intervals[narrowestIdx - 1][1] = intervals[narrowestIdx][1];
      intervals.splice(narrowestIdx, 1);
    } else {
      intervals.shift();
    }
  }

  if (intervals.length !== 4) {
    intervals = [[3, 19], [21, 37], [39, 56], [58, 75]];
  }

  const matrices: number[][][] = [];
  for (const [minX, maxX] of intervals) {
    const srcW = maxX - minX + 1;
    const norm: number[][] = Array.from({ length: CANVAS_H }, () => new Array(CANVAS_W).fill(0));

    for (let y = 2; y < Math.min(CANVAS_H + 2, height - 2); y++) {
      const ny = y - 2;
      for (let nx = 0; nx < CANVAS_W; nx++) {
        const sxMapped = minX + Math.floor((nx * srcW) / CANVAS_W);
        if (sxMapped >= 0 && sxMapped < width && grid[y][sxMapped] === 1) {
          norm[ny][nx] = 1;
        }
      }
    }

    // 连通分量 (CCA) 剥离顶部悬浮横线与孤立噪点
    const visited: boolean[][] = Array.from({ length: CANVAS_H }, () => new Array(CANVAS_W).fill(false));
    const components: [number, number][][] = [];

    for (let y = 0; y < CANVAS_H; y++) {
      for (let x = 0; x < CANVAS_W; x++) {
        if (norm[y][x] === 1 && !visited[y][x]) {
          const comp: [number, number][] = [];
          const queue: [number, number][] = [[y, x]];
          visited[y][x] = true;

          while (queue.length > 0) {
            const [cy, cx] = queue.shift()!;
            comp.push([cy, cx]);

            for (let dy = -1; dy <= 1; dy++) {
              for (let dx = -1; dx <= 1; dx++) {
                const ny = cy + dy;
                const nx = cx + dx;
                if (ny >= 0 && ny < CANVAS_H && nx >= 0 && nx < CANVAS_W && norm[ny][nx] === 1 && !visited[ny][nx]) {
                  visited[ny][nx] = true;
                  queue.push([ny, nx]);
                }
              }
            }
          }
          components.push(comp);
        }
      }
    }

    if (components.length > 1) {
      components.sort((a, b) => b.length - a.length);
      const maxComp = components[0];

      for (let i = 1; i < components.length; i++) {
        const comp = components[i];
        if (comp !== maxComp && comp.length < 14) {
          const minY = Math.min(...comp.map((p) => p[0]));
          const maxY = Math.max(...comp.map((p) => p[0]));
          if (minY < 7 && maxY < 8) {
            for (const [py, px] of comp) {
              norm[py][px] = 0;
            }
          }
        }
      }
    }

    matrices.push(norm);
  }

  return matrices;
}

/**
 * 快速位运算计算两矩阵的 Jaccard 相似度。
 */
function calculateSimilarity(mat: number[][], templateRows: number[]): number {
  let intersection = 0;
  let union = 0;

  for (let y = 0; y < CANVAS_H; y++) {
    let matRowVal = 0;
    for (let x = 0; x < CANVAS_W; x++) {
      if (mat[y][x] === 1) {
        matRowVal |= (1 << (CANVAS_W - 1 - x));
      }
    }
    const tRowVal = templateRows[y];

    const inter = matRowVal & tRowVal;
    const uni = matRowVal | tRowVal;

    intersection += countSetBits(inter);
    union += countSetBits(uni);
  }

  return union > 0 ? intersection / union : 0;
}

/**
 * 快速位计数 (Brian Kernighan's Algorithm)。
 */
function countSetBits(n: number): number {
  let count = 0;
  let val = n;
  while (val > 0) {
    val &= (val - 1);
    count++;
  }
  return count;
}

/**
 * 对单个 14x36 字符矩阵进行分类并施加拓扑物理约束。
 */
function classifyBlock(mat: number[][]): [string, number] {
  let topPixels = 0;
  let botPixels = 0;

  for (let y = 0; y < CANVAS_H; y++) {
    for (let x = 0; x < CANVAS_W; x++) {
      if (mat[y][x] === 1) {
        if (y < 8) topPixels++;
        if (y > 26) botPixels++;
      }
    }
  }

  let bestChar = '?';
  let bestScore = -1;

  for (const [ch, tList] of Object.entries(TEMPLATES)) {
    for (const tRows of tList) {
      let s = calculateSimilarity(mat, tRows);

      // 物理拓扑硬约束 (升部与降部)
      if (['h', 'b', 'd', 'k', 'l', '1', 't'].includes(ch) && botPixels > 12) {
        s *= 0.2;
      } else if (['g', 'j', 'p', 'q', 'y'].includes(ch) && botPixels < 6) {
        s *= 0.2;
      } else if (['a', 'c', 'e', 'm', 'n', 'o', 'r', 's', 'u', 'v', 'w', 'x', 'z'].includes(ch) && (topPixels > 12 || botPixels > 12)) {
        s *= 0.3;
      }

      if (s > bestScore) {
        bestScore = s;
        bestChar = ch;
      }
    }
  }

  return [bestChar, bestScore];
}

/**
 * 解析 RGBA 图像数据中的强智教务验证码。
 *
 * @param rgbaData 图像的 RGBA 原始字节数组
 * @param width 图像宽度
 * @param height 图像高度
 * @returns 识别结果对象，包含文本、置信度与可靠性评估
 */
export function recognizeCaptchaRgba(
  rgbaData: Uint8ClampedArray | Uint8Array,
  width: number,
  height: number
): OcrResult {
  const grid = preprocessPixels(rgbaData, width, height);
  const mats = extractTypographyBlocks(grid, width, height);

  let text = '';
  const charConfidences: number[] = [];

  for (const mat of mats) {
    const [ch, score] = classifyBlock(mat);
    text += ch;
    charConfidences.push(score);
  }

  const avgConfidence = charConfidences.length > 0
    ? charConfidences.reduce((a, b) => a + b, 0) / charConfidences.length
    : 0;

  const isReliable = charConfidences.every((s) => s >= 0.65) && avgConfidence >= 0.80;

  return {
    text,
    confidence: avgConfidence,
    charConfidences,
    isReliable,
  };
}

/**
 * 封装给外部业务（如 autoLogin.ts、loginView.ts）的统一验证码识别门面类。
 */
export class CaptchaOCR {
  /**
   * 识别验证码输入源并返回 4 位英数字符串。
   *
   * @param input Blob / ArrayBuffer / Base64 数据字符串
   * @returns 识别得到的 4 位文本
   */
  static async recognize(input: Blob | ArrayBuffer | string): Promise<string> {
    const result = await this.recognizeWithDetails(input);
    return result.text;
  }

  /**
   * 识别验证码输入源并返回带有置信度指标的完整结果对象。
   *
   * @param input Blob / ArrayBuffer / Base64 数据字符串
   * @returns 识别结果对象
   */
  static async recognizeWithDetails(input: Blob | ArrayBuffer | string): Promise<OcrResult> {
    if (typeof document === 'undefined') {
      return { text: '', confidence: 0, charConfidences: [], isReliable: false };
    }

    const img = new Image();
    let blobUrl = '';

    if (typeof input === 'string') {
      img.src = input.startsWith('data:') ? input : `data:image/jpeg;base64,${input}`;
    } else if (input instanceof Blob) {
      blobUrl = URL.createObjectURL(input);
      img.src = blobUrl;
    } else if (input instanceof ArrayBuffer) {
      const b = new Blob([input], { type: 'image/jpeg' });
      blobUrl = URL.createObjectURL(b);
      img.src = blobUrl;
    }

    await new Promise<void>((resolve, reject) => {
      img.onload = () => resolve();
      img.onerror = () => reject(new Error('Failed to load captcha image into element'));
    });

    if (blobUrl) {
      URL.revokeObjectURL(blobUrl);
    }

    const canvas = document.createElement('canvas');
    canvas.width = img.naturalWidth || img.width;
    canvas.height = img.naturalHeight || img.height;
    const ctx = canvas.getContext('2d');
    if (!ctx) {
      throw new Error('Cannot get 2d context for captcha decoding');
    }

    ctx.drawImage(img, 0, 0);
    const imgData = ctx.getImageData(0, 0, canvas.width, canvas.height);
    return recognizeCaptchaRgba(imgData.data, canvas.width, canvas.height);
  }
}
